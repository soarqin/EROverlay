"""Compile the shared IDA signatures into runtime Pattern16 rules (no EXE addresses)."""

import argparse
import json
from pathlib import Path


def pattern(raw, mask):
    assert len(raw) == len(mask) and all(byte in (0, 255) for byte in mask)
    return [f"{byte:02X}" if keep else "??" for byte, keep in zip(raw, mask)]


def literal(tokens, indent):
    return "\n".join(indent + '"' + " ".join(tokens[i:i + 40]) + (' "' if i + 40 < len(tokens) else '"')
                     for i in range(0, len(tokens), 40))


def render_rule(role, variant):
    assert len(variant["anchors"]) == 2
    lines = ["    {", "        Role::" + role + ",", "        {"]
    for anchor in variant["anchors"]:
        tokens = pattern(bytes.fromhex(anchor["bytes"]), bytes.fromhex(anchor["mask"]))
        lines.extend(["            {", literal(tokens, "                ") + ",",
                      f"                {anchor['byte_offset']}", "            },"])
    lines.append("        },")
    body = variant.get("body_contract", [])
    if body:
        tokens = []
        length = body[-1]["offset"] + body[-1]["size"]
        for instruction in body:
            assert instruction["offset"] == len(tokens)
            raw = bytes.fromhex(instruction["bytes"])
            mask = bytearray.fromhex(instruction["mask"])
            assert len(raw) == instruction["size"]
            # Preserve internal branch targets. Only relocatable calls,
            # RIP operands and branches out of this body stay masked.
            displacement = 0
            if raw[0] == 0xE9 or (len(raw) >= 2 and raw[0] == 0x0F and 0x80 <= raw[1] <= 0x8F):
                displacement = len(raw) - 4
            elif raw[0] == 0xEB or 0x70 <= raw[0] <= 0x7F or 0xE0 <= raw[0] <= 0xE3:
                displacement = len(raw) - 1
            if displacement:
                target = instruction["offset"] + len(raw) + int.from_bytes(raw[displacement:], "little", signed=True)
                if 0 <= target < length:
                    mask[displacement:] = b"\xff" * (len(raw) - displacement)
            tokens.extend(pattern(raw, mask))
        lines.append(literal(tokens, "        ") + ",")
    else:
        lines.append("        nullptr,")
    calls = [i["offset"] for i in body if i["size"] == 5 and bytes.fromhex(i["bytes"])[0] == 0xE8]
    assert len(calls) <= 8
    lines.extend(["        {" + ", ".join(map(str, calls)) + "},", "        " + str(len(calls)), "    },"])
    return "\n".join(lines)


def render(source):
    lines = ["// Generated by tools/generate_minimap_scan_rules.py from the shared IDA rules.",
             "// No executable hashes, version choices or absolute/relative addresses.",
             "enum class Role {"]
    names = {name: "".join(part.title() for part in name.split("_")) for name in source}
    lines.extend("    " + name + "," for name in names.values())
    lines.extend(["    Count", "};", "", "struct Anchor {", "    const char *pattern;", "    uint32_t offset;", "};",
                  "struct Rule {", "    Role role;", "    Anchor anchors[2];", "    const char *body;", "    uint32_t calls[8];", "    uint32_t callCount;", "};", "",
                  "inline constexpr Rule RULES[] = {"])
    for name, variants in source.items():
        # Different EXEs can produce identical rules after masking relocations.
        # Preserve their first occurrence without scanning the same rule twice.
        lines.extend(dict.fromkeys(render_rule(names[name], variant) for variant in variants))
    lines.extend(["};", "", "inline constexpr const char *ROLE_NAMES[] = {"])
    lines.extend('    "' + name + '",' for name in names)
    lines.extend(["};", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("docs/minimap-scanner-signatures.json"))
    parser.add_argument("--output", type=Path, default=Path("src/util/minimap_scan_rules.inc"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render(json.loads(args.source.read_text(encoding="utf-8")))
    if args.check:
        assert args.output.read_text(encoding="utf-8") == content, "Regenerate minimap_scan_rules.inc"
    else:
        args.output.write_text(content, encoding="utf-8", newline="\n")
    print("PASS: runtime rules match the shared IDA signatures")


if __name__ == "__main__":
    main()
